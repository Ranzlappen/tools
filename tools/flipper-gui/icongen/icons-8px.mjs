/* Pack one icon's 8×8 art into base64 XBM, matching lib/xbm.js's format so
 * it's byte-identical to every other library/uploaded icon. */
export function pack8(name) {
  const rows = ART_8[name];
  if (!rows || rows.length !== 8 || rows.some((r) => r.length !== 8)) {
    throw new Error(`8×8 art for "${name}" must be exactly 8 rows of 8 chars`);
  }
  const px = new Uint8Array(64);
  for (let y = 0; y < 8; y++) {
    for (let x = 0; x < 8; x++) px[y * 8 + x] = rows[y][x] === "#" ? 1 : 0;
  }
  return bytesToB64(packXbm(px, 8, 8));
}
